#ifndef BUTTONS_H
#define BUTTONS_H

#include <Arduino.h>

// ============================================================================
// СТРУКТУРА BUTTON - ХРАНЕНИЕ СОСТОЯНИЯ ОДНОЙ КНОПКИ
// ============================================================================
// struct - как class, но все члены по умолчанию публичные (доступны всем)
// Используем struct для простых группировок данных без методов
struct Button {
    uint8_t pin;                    // Номер пина, к которому подключена кнопка
    bool lastState;                 // Последнее прочитанное состояние (для антидребезга)
    bool currentState;              // Текущее стабильное состояние (после антидребезга)
    unsigned long lastDebounceTime; // Время последнего изменения состояния (мс)
    bool wasPressed;                // Флаг: true - нажатие уже обработано программой
};

// ============================================================================
// КЛАСС BUTTONS - УПРАВЛЕНИЕ ТРЕМЯ КНОПКАМИ
// ============================================================================
class Buttons {
  public:
    // --- ИНИЦИАЛИЗАЦИЯ ------------------------------------------------------
    // Принимает номера пинов для трёх кнопок: уменьшение, старт, увеличение
    void begin(uint8_t decreasePin, uint8_t startPin, uint8_t increasePin);
    
    // --- ОБНОВЛЕНИЕ (ВЫЗЫВАТЬ В LOOP) --------------------------------------
    // Читает состояния пинов, обрабатывает антидребезг
    void update();
    
    // --- ПРОВЕРКА ФРОНТА НАЖАТИЯ (ОДНОКРАТНО) ------------------------------
    // Возвращает true ТОЛЬКО В МОМЕНТ, когда кнопка была нажата
    // После этого сбрасывает флаг, чтобы не срабатывало повторно
    bool isStartPressed();
    bool isIncreasePressed();
    bool isDecreasePressed();
    
    // --- ПРОВЕРКА УДЕРЖАНИЯ (ДЛЯ ПЛАВНОГО ИЗМЕНЕНИЯ) -----------------------
    // Возвращает true, если кнопка удерживается дольше HOLD_DELAY
    // Затем срабатывает каждые HOLD_INTERVAL миллисекунд
    // Это позволяет менять значение с ускорением при долгом удержании
    bool isIncreaseHeld();
    bool isDecreaseHeld();
  
  private:
    // Три структуры Button для хранения состояния каждой кнопки
    Button _btnDecrease;   // Кнопка уменьшения уставки (пин 6)
    Button _btnStart;      // Кнопка старт/стоп (пин 9)
    Button _btnIncrease;   // Кнопка увеличения уставки (пин 10)
    
    // --- ВСПОМОГАТЕЛЬНЫЙ МЕТОД ---------------------------------------------
    // Обновляет состояние одной кнопки (логика антидребезга)
    // Принимает ссылку на структуру Button (символ & означает "по ссылке")
    // Передача по ссылке позволяет изменять оригинал, а не копию
    void updateButton(Button& btn);
    
    // --- КОНСТАНТЫ ДЛЯ АНТИДРЕБЕЗГА И АВТОПОВТОРА --------------------------
    // const - значение не может быть изменено после инициализации
    // unsigned long - тип для хранения больших чисел (до 4,294,967,295)
    
    // Задержка антидребезга: 50 миллисекунд
    // За это время сигнал на пине должен стабилизироваться
    const unsigned long DEBOUNCE_DELAY = 50;
    
    // Задержка перед началом автоповтора: 400 мс
    // Если держать кнопку дольше этого времени, начнёт срабатывать многократно
    const unsigned long HOLD_DELAY = 400;
    
    // Интервал автоповтора: 100 мс
    // После начала автоповтора срабатывает каждые 100 мс
    const unsigned long HOLD_INTERVAL = 100;
    
    // Время начала удержания кнопки увеличения (0 - не удерживается)
    unsigned long _lastIncreaseHold;
    
    // Время начала удержания кнопки уменьшения
    unsigned long _lastDecreaseHold;

    // Время последнего шага автоповтора для ровного изменения уставки
    unsigned long _lastIncreaseRepeat;
    unsigned long _lastDecreaseRepeat;
};

#endif

// и пропустит всё содержимое (предотвращает повторное объявление)
#define CONFIG_H

// ============================================================================
// ПИНЫ ДЛЯ ЗУММЕРА
// ============================================================================
// #define BUZZER_PIN 3 - создаёт константу с именем BUZZER_PIN и значением 3

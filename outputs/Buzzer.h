#ifndef BUZZER_H
#define BUZZER_H

// ============================================================================
// ПОДКЛЮЧЕНИЕ БИБЛИОТЕКИ ARDUINO
// ============================================================================
// <Arduino.h> - основная библиотека Arduino, содержит определения всех функций
// pinMode(), digitalWrite(), millis() и так далее
// Без неё компилятор не поймёт, что такое uint8_t, HIGH, LOW и т.д.
#include <Arduino.h>

// ============================================================================
// ОБЪЯВЛЕНИЕ КЛАССА BUZZER
// ============================================================================
// class - ключевое слово для создания класса (пользовательского типа данных)
// Класс объединяет данные (переменные) и методы (функции) для работы с ними
class Buzzer {
  
  // ==========================================================================
  // PUBLIC: МЕТОДЫ, ДОСТУПНЫЕ ИЗ ЛЮБОГО МЕСТА ПРОГРАММЫ
  // ==========================================================================
  public:
    // --- ИНИЦИАЛИЗАЦИЯ ------------------------------------------------------
    // void - метод ничего не возвращает
    // begin - имя метода (традиция в Arduino: begin() для инициализации)
    // uint8_t pin - параметр: номер пина (unsigned 8-bit integer, 0-255)
    void begin(uint8_t pin);
    
    // --- НЕБЛОКИРУЮЩИЕ ЗВУКОВЫЕ СИГНАЛЫ ------------------------------------
    // Короткий писк (100 мс) - например, при нажатии кнопки
    void beepShort();
    
    // Длинный писк (500 мс) - например, для подтверждения действия
    void beepLong();
    
    // --- АВАРИЙНЫЙ СИГНАЛ ---------------------------------------------------
    // Включает прерывистый звук (250 мс пищит, 250 мс молчит)
    void alarmStart();
    
    // Выключает аварийный сигнал. Возврат к нормальному режиму.
    void alarmStop();
    
    // --- ОБНОВЛЕНИЕ СОСТОЯНИЯ (ДОЛЖЕН ВЫЗЫВАТЬСЯ В LOOP) -------------------
    // Проверяет, не пора ли выключить короткий писк
    // Или переключить состояние аварийного сигнала
    void update();
    
    // --- ПРОВЕРКА СОСТОЯНИЯ -------------------------------------------------
    // Возвращает true, если аварийный сигнал активен
    // Используется, чтобы, например, не давать запустить систему в аварии
    bool isAlarmActive();
  
  // ==========================================================================
  // PRIVATE: ПЕРЕМЕННЫЕ, ДОСТУПНЫЕ ТОЛЬКО ВНУТРИ КЛАССА
  // ==========================================================================
  // Пользователь не может их изменить напрямую, только через методы
  private:
    // Номер пина, к которому подключён зуммер
    uint8_t _pin;  // подчёркивание в начале - традиция для приватных переменных
    
    // --- ПЕРЕМЕННЫЕ ДЛЯ НЕБЛОКИРУЮЩЕГО КОРОТКОГО ПИСКА --------------------
    // Флаг: true - сейчас воспроизводится короткий/длинный писк
    bool _beepActive;
    
    // Время (в миллисекундах), когда писк начался
    unsigned long _beepStartTime;  // unsigned long - 32 бита, до 49 дней
    
    // Длительность писка в миллисекундах (100 или 500)
    unsigned long _beepDuration;
    
    // --- ПЕРЕМЕННЫЕ ДЛЯ АВАРИЙНОГО СИГНАЛА --------------------------------
    // Флаг активности аварийного сигнала
    bool _alarmActive;
    
    // Время последнего переключения (включили/выключили звук)
    unsigned long _lastAlarmToggle;
    
    // Текущее состояние аварийного сигнала: true - звук включён, false - выключен
    bool _alarmState;
    
    // Длительность включенного состояния аварийного сигнала (мс)
    // 250 мс - звук включён
    unsigned long _alarmOnTime;
    
    // Длительность выключенного состояния аварийного сигнала (мс)
    // 250 мс - пауза, затем повтор
    unsigned long _alarmOffTime;
};

// Закрываем блок #ifndef
#endif

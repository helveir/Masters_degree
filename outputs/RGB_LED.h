#ifndef RGB_LED_H
#define RGB_LED_H

#include <Arduino.h>

// ============================================================================
// КЛАСС RGB_LED - УПРАВЛЕНИЕ ТРЁХЦВЕТНЫМ СВЕТОДИОДОМ
// ============================================================================
class RGB_LED {
  public:
    // --- ИНИЦИАЛИЗАЦИЯ ------------------------------------------------------
    // Принимает три номера пинов: для красного, зелёного и синего каналов
    void begin(uint8_t redPin, uint8_t greenPin, uint8_t bluePin);
    
    // --- ПРЕДУСТАНОВЛЕННЫЕ СОСТОЯНИЯ ----------------------------------------
    // "Готов" - зелёный свет (система в режиме ожидания)
    void setReady();
    
    // "Работа" - синий свет (активный процесс налива/отсоса)
    void setWorking();
    
    // "Авария" - красный свет (критическая ситуация)
    void setAlarm();
    
    // "Выключен" - все каналы выключены
    void setOff();
    
    // --- ПРЯМОЕ УПРАВЛЕНИЕ ЦВЕТОМ -------------------------------------------
    // Позволяет задать произвольный цвет
    // r, g, b - могут быть HIGH (5V) или LOW (0V)
    // Для обычного светодиода без ШИМ только 8 комбинаций цветов
    void setColor(uint8_t r, uint8_t g, uint8_t b);
  
  private:
    // Храним номера пинов для каждого канала
    uint8_t _redPin;
    uint8_t _greenPin;
    uint8_t _bluePin;
};

#endif

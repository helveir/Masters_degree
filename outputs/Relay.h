#ifndef RELAY_H
#define RELAY_H

#include <Arduino.h>

// ============================================================================
// КЛАСС RELAY - УПРАВЛЕНИЕ ДВУМЯ РЕЛЕ (КЛАПАНАМИ)
// ============================================================================
class Relay {
  public:
    // --- ИНИЦИАЛИЗАЦИЯ ------------------------------------------------------
    // feedPin - пин для реле подачи воздуха (повышает давление)
    // suctionPin - пин для реле отсоса воздуха (понижает давление)
    void begin(uint8_t feedPin, uint8_t suctionPin);
    
    // --- УПРАВЛЕНИЕ КЛАПАНОМ ПОДАЧИ -----------------------------------------
    void feedOn();      // Включить подачу (открыть клапан)
    void feedOff();     // Выключить подачу (закрыть клапан)
    
    // --- УПРАВЛЕНИЕ КЛАПАНОМ ОТСОСА -----------------------------------------
    void suctionOn();   // Включить отсос
    void suctionOff();  // Выключить отсос
    
    // --- ГРУППОВЫЕ ОПЕРАЦИИ -------------------------------------------------
    void bothOff();     // Выключить ОБА клапана (безопасное состояние)
    
    // --- ПРОВЕРКА СОСТОЯНИЯ -------------------------------------------------
    // Возвращает true, если клапан включён
    bool isFeedActive();
    bool isSuctionActive();
  
  private:
    // Номера пинов реле
    uint8_t _feedPin;
    uint8_t _suctionPin;
    
    // Флаги состояния (true - включено, false - выключено)
    // Нужны, чтобы быстро узнать состояние без digitalRead()
    bool _feedState;
    bool _suctionState;
};

#endif

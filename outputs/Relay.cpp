#include "Relay.h"

// ============================================================================
// BEGIN - ИНИЦИАЛИЗАЦИЯ РЕЛЕ
// ============================================================================
void Relay::begin(uint8_t feedPin, uint8_t suctionPin) {
    // Сохраняем номера пинов
    _feedPin = feedPin;
    _suctionPin = suctionPin;
    
    // Инициализируем флаги состояния: начинаем с выключенного
    _feedState = false;
    _suctionState = false;
    
    // Настраиваем пины как выходы (будем подавать напряжение для включения реле)
    pinMode(_feedPin, OUTPUT);
    pinMode(_suctionPin, OUTPUT);
    
    // Выключаем оба реле - безопасное начальное состояние
    bothOff();
}

// ============================================================================
// FEED ON - ВКЛЮЧИТЬ КЛАПАН ПОДАЧИ
// ============================================================================
void Relay::feedOn() {
    // Подаём HIGH (5 вольт) на пин реле
    // Реле срабатывает и замыкает цепь клапана
    digitalWrite(_feedPin, HIGH);
    
    // Запоминаем состояние
    _feedState = true;
}

// ============================================================================
// FEED OFF - ВЫКЛЮЧИТЬ КЛАПАН ПОДАЧИ
// ============================================================================
void Relay::feedOff() {
    // Подаём LOW (0 вольт) - реле выключается
    digitalWrite(_feedPin, LOW);
    _feedState = false;
}

// ============================================================================
// SUCTION ON - ВКЛЮЧИТЬ КЛАПАН ОТСОСА
// ============================================================================
void Relay::suctionOn() {
    digitalWrite(_suctionPin, HIGH);
    _suctionState = true;
}

// ============================================================================
// SUCTION OFF - ВЫКЛЮЧИТЬ КЛАПАН ОТСОСА
// ============================================================================
void Relay::suctionOff() {
    digitalWrite(_suctionPin, LOW);
    _suctionState = false;
}

// ============================================================================
// BOTH OFF - ВЫКЛЮЧИТЬ ОБА КЛАПАНА
// ============================================================================
void Relay::bothOff() {
    feedOff();     // Выключаем подачу
    suctionOff();  // Выключаем отсос
}

// ============================================================================
// IS FEED ACTIVE - ПРОВЕРКА СОСТОЯНИЯ КЛАПАНА ПОДАЧИ
// ============================================================================
bool Relay::isFeedActive() {
    return _feedState;   // Просто возвращаем сохранённое значение
}

// ============================================================================
// IS SUCTION ACTIVE - ПРОВЕРКА СОСТОЯНИЯ КЛАПАНА ОТСОСА
// ============================================================================
bool Relay::isSuctionActive() {
    return _suctionState;
}

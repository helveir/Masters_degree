#ifndef DISPLAY_H
#define DISPLAY_H

// ============================================================================
// ПОДКЛЮЧЕНИЕ БИБЛИОТЕК ДЛЯ РАБОТЫ С OLED ДИСПЛЕЕМ
// ============================================================================
// Wire.h - библиотека для работы с шиной I2C (пины A4=SDA, A5=SCL на Arduino Nano)
#include <Wire.h>

// Adafruit_GFX.h - основная графическая библиотека (рисует точки, линии, текст)
// Предоставляет базовые примитивы для работы с дисплеями
#include <Adafruit_GFX.h>

// Adafruit_SSD1306.h - библиотека для конкретного чипа SSD1306 (OLED 128x64)
// Наследуется от Adafruit_GFX, добавляет специфичные для SSD1306 команды
#include <Adafruit_SSD1306.h>

// ============================================================================
// КОНСТАНТЫ ДЛЯ НАСТРОЙКИ ДИСПЛЕЯ
// ============================================================================
// Ширина экрана в пикселях (128 пикселей по горизонтали)
#define SCREEN_WIDTH 128

// Высота экрана в пикселях (64 пикселя по вертикали)
#define SCREEN_HEIGHT 64

// I2C адрес дисплея (обычно 0x3C или 0x3D)
// 0x3C - самый распространённый адрес для OLED 128x64
// 0x3D - встречается реже, можно проверить скетчем-сканером I2C
#define OLED_ADDR 0x3C

// Пины Reset для дисплея (-1 означает, что не используется)
// Дисплей сбрасывается автоматически при подаче питания
#define OLED_RESET -1

// ============================================================================
// КЛАСС DISPLAY - УПРАВЛЕНИЕ OLED ДИСПЛЕЕМ
// ============================================================================
class Display {
  public:
    // --- ИНИЦИАЛИЗАЦИЯ ------------------------------------------------------
    // Подключается к дисплею по I2C, настраивает размеры
    // Возвращает true, если дисплей найден и инициализирован
    bool begin();
    
    // --- ОБНОВЛЕНИЕ ЭКРАНА (ВЫЗЫВАТЬ ПРИ ИЗМЕНЕНИИ ДАННЫХ) -----------------
    // Основной метод: рисует весь интерфейс заново
    // Принимает:
    //   - pressure: текущее давление (в кПа)
    //   - setpoint: целевое давление (уставка, в кПа)
    //   - systemState: состояние системы (0=ожидание, 1=работа, 2=авария)
    //   - feedActive: включён ли клапан подачи
    //   - suctionActive: включён ли клапан отсоса
    void update(int pressure, int setpoint, int systemState, 
                bool feedActive, bool suctionActive);
    
    // --- ОТОБРАЖЕНИЕ ЗАСТАВКИ ПРИ СТАРТЕ -----------------------------------
    void showSplash();
    
    // --- ОТОБРАЖЕНИЕ СООБЩЕНИЯ ОБ ОШИБКЕ (если дисплей не найден) ----------
    void showError(const char* message);
    
    // --- ПРОВЕРКА, РАБОТАЕТ ЛИ ДИСПЛЕЙ -------------------------------------
    bool isConnected();
    
  private:
    // Объект дисплея (экземпляр класса Adafruit_SSD1306)
    // Передаём ширину, высоту, ссылку на шину Wire и пин Reset
    Adafruit_SSD1306 _display = Adafruit_SSD1306(SCREEN_WIDTH, SCREEN_HEIGHT, &Wire, OLED_RESET);
    
    // Флаг, успешно ли подключён дисплей
    bool _connected;
    
    // --- ВСПОМОГАТЕЛЬНЫЕ МЕТОДЫ ДЛЯ ОТРИСОВКИ ------------------------------
    
    // Рисует рамку вокруг экрана
    void drawBorder();
    
    // Рисует шкалу давления (графический индикатор)
    // pressure: текущее давление (кПа)
    // setpoint: целевое давление (кПа)
    // minPressure: минимальное значение шкалы (-5 кПа)
    // maxPressure: максимальное значение шкалы (5 кПа)
    void drawPressureBar(int pressure, int setpoint, int minPressure, int maxPressure);
    
    // Рисует иконку состояния системы (значок)
    // state: 0-ожидание (часы), 1-работа (шестерёнка), 2-авария (крест)
    void drawStateIcon(int state);
    
    // Рисует иконки клапанов (подача, отсос)
    void drawValveIcons(bool feedActive, bool suctionActive);
};

#endif
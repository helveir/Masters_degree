#include "RGB_LED.h"

// ============================================================================
// BEGIN - ИНИЦИАЛИЗАЦИЯ RGB СВЕТОДИОДА
// ============================================================================
void RGB_LED::begin(uint8_t redPin, uint8_t greenPin, uint8_t bluePin) {
    // Сохраняем номера пинов в приватные переменные
    // Они понадобятся в других методах (setColor, setReady и т.д.)
    _redPin = redPin;
    _greenPin = greenPin;
    _bluePin = bluePin;
    
    // Настраиваем все три пина как выходы (OUTPUT)
    // OUTPUT означает, что мы будем подавать напряжение на пин
    pinMode(_redPin, OUTPUT);
    pinMode(_greenPin, OUTPUT);
    pinMode(_bluePin, OUTPUT);
    
    // Начинаем с выключенного состояния (все каналы в 0)
    setOff();
}

// ============================================================================
// SET COLOR - УСТАНОВКА ПРОИЗВОЛЬНОГО ЦВЕТА
// ============================================================================
// Принимает три значения: для красного, зелёного и синего каналов
// Каждое значение может быть HIGH (5V - светодиод горит) или LOW (0V - не горит)
void RGB_LED::setColor(uint8_t r, uint8_t g, uint8_t b) {
    // digitalWrite() - устанавливает напряжение на пине
    digitalWrite(_redPin, r);     // Устанавливаем уровень на красном пине
    digitalWrite(_greenPin, g);   // Устанавливаем уровень на зелёном пине
    digitalWrite(_bluePin, b);    // Устанавливаем уровень на синем пине
}

// ============================================================================
// SET READY - СОСТОЯНИЕ "ГОТОВ"
// ============================================================================
// Зелёный свет: красный - выкл, зелёный - вкл, синий - выкл
void RGB_LED::setReady() {
    setColor(LOW, HIGH, LOW);   // LOW = 0 вольт, HIGH = 5 вольт
}

// ============================================================================
// SET WORKING - СОСТОЯНИЕ "РАБОТА"
// ============================================================================
// Синий свет: красный - выкл, зелёный - выкл, синий - вкл
void RGB_LED::setWorking() {
    setColor(LOW, LOW, HIGH);
}

// ============================================================================
// SET ALARM - СОСТОЯНИЕ "АВАРИЯ"
// ============================================================================
// Красный свет: красный - вкл, зелёный - выкл, синий - выкл
void RGB_LED::setAlarm() {
    setColor(HIGH, LOW, LOW);
}

// ============================================================================
// SET OFF - ВЫКЛЮЧИТЬ ВСЕ СВЕТОДИОДЫ
// ============================================================================
void RGB_LED::setOff() {
    setColor(LOW, LOW, LOW);    // Все каналы выключены
}